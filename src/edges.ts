/*
  Curated tradeoff edges.

  Each edge says: increasing `source` tends to push `target` in a given
  direction, with `influence` on a qualitative 1x, 2x, 3x, or 5x scale.
  This is opinionated, not scientific. Most edges are intuited from the canonical definitions; a
  small set inherits from the original Coda data and is marked `inherited`.

  The matching half-edge (target -> source) is NOT auto-symmetric. We
  encode only the directional claim "moving the source tends to drag the
  target along". The reverse direction is its own edge if it exists.

  When two selected sources both affect the same target, deltas combine
  additively with sign and clamp to ±100. See `tradeoff.ts`.
*/

export type EdgeDirection = 'positive' | 'negative'

export type EdgeConfidence = 'curated' | 'inherited' | 'inferred' | 'inherent'

export type EdgeInfluence = 1 | 2 | 3 | 5

export type Edge = {
  readonly source: string
  readonly target: string
  readonly direction: EdgeDirection
  readonly influence: EdgeInfluence
  readonly confidence: EdgeConfidence
  readonly note?: string
}

